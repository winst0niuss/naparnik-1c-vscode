/** «/init аргументы» → { name: 'init', args: 'аргументы' }; не команда — undefined */
export function parseSlash(text: string): { name: string; args: string } | undefined {
  const m = text.trim().match(/^\/([\w-]+)(?:\s+([\s\S]*))?$/);
  return m ? { name: m[1].toLowerCase(), args: (m[2] ?? '').trim() } : undefined;
}

export function helpText(): string {
  return ['**Команды:**', ...SLASH_COMMANDS.map((c) => `- \`/${c.name}${c.args ? ' ' + c.args : ''}\` — ${c.description}`)].join('\n');
}

